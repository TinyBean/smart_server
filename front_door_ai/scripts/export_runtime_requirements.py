"""Export the locked production dependencies without application-version metadata."""

import argparse
import subprocess
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
TARGET = PROJECT / "requirements-runtime.txt"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed export is stale")
    args = parser.parse_args()
    result = subprocess.run(
        ["uv", "export", "--locked", "--offline", "--no-dev", "--all-extras",
         "--no-emit-project", "--no-header", "--no-annotate"],
        cwd=PROJECT, check=True, stdout=subprocess.PIPE, text=True, encoding="utf-8",
    )
    content = "# Generated by scripts/export_runtime_requirements.py; do not edit.\n" + result.stdout
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("Runtime requirements are stale. Run: python scripts/export_runtime_requirements.py")
        print("Runtime requirements match uv.lock (all extras, no development or project package).")
    else:
        TARGET.write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {TARGET.name}")


if __name__ == "__main__":
    main()
